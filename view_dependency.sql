col TABLE_NAME for a30
col OBJECT_TYPE for a10
col REFERENCED_OWNER for a20
col REFERENCED_NAME for a30
SELECT 
    d.OWNER AS TABLE_OWNER,
    d.NAME AS TABLE_NAME,
    d.TYPE AS OBJECT_TYPE,
    d.REFERENCED_OWNER AS REFERENCED_OWNER,
    d.REFERENCED_NAME AS REFERENCED_NAME,
    d.REFERENCED_TYPE AS REFERENCED_TYPE
FROM 
    DBA_DEPENDENCIES d
WHERE 
    d.TYPE = 'VIEW' 
    AND d.NAME = '&view_name'  -- Replace with your view name
    AND d.REFERENCED_TYPE IN ('TABLE', 'VIEW')
ORDER BY 
    d.OWNER, d.NAME;
